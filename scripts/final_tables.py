def heldout_table(held, hspec, args, test: pd.DataFrame | None) -> None:
    models = list(hspec["models"])
    flows = list(dict.fromkeys(held["condition"]))

    def overall(m, metric):  # per seed: mean over the flows; then over seeds
        g = held[held["model"] == m].groupby("seed")[metric].mean()
        return summarise(g.sort_index().astype(float).tolist())

    lines = header(
        f"Generalisation — {hspec['dataset']} `{hspec['split']}`, zero-shot (ROADMAP 7.4)",
        hspec,
        "Models trained on the Jinan train flow only; τ from Jinan validation; no Hangzhou "
        "flow was simulated before this run. Hangzhou has 16 intersections (Jinan 12). "
        "\"All flows\" = for each seed the mean over the flows, then mean ± std [95 % CI] "
        "over seeds.",
    )
    for metric, title, digits in ((ATT, "Average travel time (s)", 1),
                                  (MAXW, "Maximum per-vehicle wait (s)", 0),
                                  ("throughput_veh", "Throughput (veh)", 0),
                                  ("fallback_rate", "Fallback rate", 3)):  # fmt: skip
        rows = [[label(m), *(cell(held, m, f, metric, digits) for f in flows),
                 fmt(overall(m, metric), digits)] for m in models]  # fmt: skip
        if "idqn" not in models:
            rows.insert(min(3, len(rows)), ["IDQN", *["not transferable"] * (len(flows) + 1)])
        lines += [f"## {title}", "", *md_table(["Model", *flows, "All flows"], rows)]
    lines += [
        "IDQN has one network per Jinan intersection, so it cannot be applied to another "
        "road network without retraining; this is a property of independent learners, not a "
        "missing run.",
        "",
    ]
    rank_h = sorted(models, key=lambda m: overall(m, ATT)["mean"])
    lines += ["## Order of the models (lowest travel time first)", ""]
    rows = [["Hangzhou (all flows)", " < ".join(label(m) for m in rank_h)]]
    if test is not None:
        both = [m for m in models if m in set(test["model"])]
        rank_t = sorted(both, key=lambda m: np.mean(vals(test, m, "clean", ATT)))
        rows.append(["Jinan test (clean)", " < ".join(label(m) for m in rank_t)])
    lines += md_table(["Data", "Order"], rows)
    metrics = [ATT, WAIT, MAXW, "throughput_veh", "fallback_rate"]
    st = stats_frame(held, metrics)
    write(args.out_dir, "heldout_generalisation", lines, st)
    # the "All flows" column as data (read by scripts/report_tables.py); same columns as `st`
    rows = []
    for m in models:
        n = held[held["model"] == m]["seed"].nunique()
        row = {"model": m, "condition": "all", "n_seeds": n}
        for metric in metrics:
            s = overall(m, metric)
            row.update({f"{metric}_{k}": s[k] for k in ("mean", "std", "ci95_low", "ci95_high")})
        rows.append(row)
    pd.DataFrame(rows).to_csv(args.out_dir / "heldout_generalisation_all.csv", index=False)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--study", choices=("test", "heldout", "all"), default="all")
    ap.add_argument("--test-spec", type=Path, default=REPO_ROOT / "configs" / "final_test.yaml")
    ap.add_argument(
        "--heldout-spec", type=Path, default=REPO_ROOT / "configs" / "final_heldout.yaml"
    )
    ap.add_argument("--results-dir", type=Path, default=REPO_ROOT / "results" / "final")
    ap.add_argument("--train-dir", type=Path, default=REPO_ROOT / "results" / "train")
    ap.add_argument("--out-dir", type=Path, default=REPO_ROOT / "docs" / "results")
    ap.add_argument("--prefix", help="file prefix of the test-study tables (default: its split)")
    ap.add_argument(
        "--val-table", type=Path, default=REPO_ROOT / "docs" / "results" / "val_phase6.csv"
    )
    args = ap.parse_args(argv)

    test = held = None
    try:
        if args.study in ("test", "all"):
            tspec = read_yaml(args.test_spec)
            test = load_study(tspec, args.results_dir / tspec["study"])
        if args.study in ("heldout", "all"):
            hspec = read_yaml(args.heldout_spec)
            held = load_study(hspec, args.results_dir / hspec["study"])
    except FileNotFoundError as e:
        print(f"error: {e}", file=sys.stderr)
        return 1

    verdicts: dict = {}
    if test is not None:
        prefix = args.prefix or tspec["split"]
        verdicts.update(main_table(test, tspec, args, prefix))
        ablation_table(test, tspec, args, prefix)
        verdicts.update(robustness_table(test, tspec, args, prefix))
        efficiency_table(test, tspec, args, prefix, held)
        safety_table(test, tspec, args, prefix, held)
    if held is not None:
        heldout_table(held, hspec, args, test)
    for k, v in verdicts.items():
        print(f"{k}: {v}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
