"""Phase 7 result tables from the finished final studies (ROADMAP 7.1–7.6).

    python scripts/final_tables.py --study all            # after both final studies
    python scripts/final_tables.py --study test --test-spec SPEC --prefix smoke --out-dir DIR

Pure reader: it never runs a simulation, so it can be repeated without touching the test or
held-out flows. Reads ``<results-dir>/<study>/eval/<model>__<condition>/<run>/`` written by
``scripts/robustness.py`` (``metrics.csv``, ``decisions_s*.csv``), the training summaries and
the validation table, and writes under ``--out-dir`` (default ``docs/results``):

* ``<prefix>_main``            7.1  Model | Validation | Test | Training time | Params + verdicts
* ``<prefix>_ablation``        7.2  full vs −gate / −attention / −ensemble
* ``<prefix>_robustness``      7.3  model × condition, regret, H2
* ``heldout_generalisation``   7.4  model × Hangzhou flow, zero-shot
* ``<prefix>_efficiency``      7.5  latency, training time, parameters, checkpoint size
* ``<prefix>_safety_explain``  7.6  wait tail, fallback, gate and attention statistics

The hypothesis verdicts follow the rules fixed before the runs
(:mod:`trafficrl.eval.hypotheses`). Attention and gate statistics are associations.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd

from trafficrl.data.splits import REPO_ROOT
from trafficrl.eval import hypotheses as hyp
from trafficrl.eval.report import fmt, load_study, training_summaries
from trafficrl.utils.config import read_yaml
from trafficrl.utils.plotting import CONTROLLER_LABEL
from trafficrl.utils.stats import summarise

AGENTS = ("fixed_time", "max_pressure", "dqn", "idqn", "ugmarl")
VARIANTS = ("ugmarl", "ugmarl-nogate", "ugmarl-noattn", "ugmarl-noens")
RULES = ("fixed_time", "max_pressure")
ATT, WAIT, MAXW = "avg_travel_time_s", "avg_waiting_time_s", "max_waiting_time_s"
NOISE = "noise0.2"
SLOTS = ("self", "E", "N", "W", "S")


def label(model: str) -> str:
    return CONTROLLER_LABEL.get(model, model)


def train_model(spec: dict, model: str) -> str:
    return (spec["models"][model] or {}).get("train_model", model)


def vals(df: pd.DataFrame, model: str, cond: str, metric: str) -> list[float]:
    g = df[(df["model"] == model) & (df["condition"] == cond)].sort_values("seed")
    return g[metric].astype(float).tolist()


def cell(df: pd.DataFrame, model: str, cond: str, metric: str, digits: int = 1) -> str:
    v = vals(df, model, cond, metric)
    return fmt(summarise(v), digits) if v else "—"


def md_table(head: list[str], rows: list[list[str]]) -> list[str]:
    return [
        "| " + " | ".join(head) + " |",
        "|" + "---|" * len(head),
        *("| " + " | ".join(str(c) for c in r) + " |" for r in rows),
        "",
    ]


def header(title: str, spec: dict, extra: str = "") -> list[str]:
    final = spec["split"] in ("test", "heldout")
    return [
        f"# {title}",
        "",
        f"Generated by `scripts/final_tables.py` from study `{spec['study']}` "
        f"({spec['dataset']} `{spec['split']}`, 3600 s, Δt = 15 s, seeds "
        f"{', '.join(str(s) for s in spec['seeds'])}; a learned model's seed s uses the "
        "checkpoint trained with seed s, gated UG-MARL uses τ from its `gate.json`). "
        "Mean ± std [95 % CI, Student t] over seeds. "
        + (
            "**Final evaluation: every episode was run once, with the models locked on "
            "validation (`models/manifest.json`); nothing is selected from this table.**"
            if final
            else "**Not a final result** (smoke / validation run of the Phase 7 pipeline)."
        )
        + (" " + extra if extra else ""),
        "",
    ]


def write(out_dir: Path, name: str, lines: list[str], table: pd.DataFrame) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / f"{name}.md").write_text("\n".join(lines).rstrip("\n") + "\n")
    table.to_csv(out_dir / f"{name}.csv", index=False)
    print(f"wrote {out_dir / name}.md")


def stats_frame(df: pd.DataFrame, metrics: list[str]) -> pd.DataFrame:
    """Long table: one row per (model, condition) with mean / std / CI of every metric."""
    rows = []
    for (model, cond), g in df.groupby(["model", "condition"], sort=False):
        row = {"model": model, "condition": cond, "n_seeds": len(g)}
        for m in metrics:
            if m in g and g[m].notna().any():
                s = summarise(g.sort_values("seed")[m].astype(float).tolist())
                row.update({f"{m}_{k}": s[k] for k in ("mean", "std", "ci95_low", "ci95_high")})
        rows.append(row)
    return pd.DataFrame(rows)


# --- 7.1 main comparison ---------------------------------------------------------------


def main_table(df, spec, args, prefix) -> dict:
    agents = [m for m in AGENTS if m in spec["models"]]
    val = pd.read_csv(args.val_table).set_index("model") if args.val_table.is_file() else None
    seeds = spec["seeds"]
    rows, recs = [], []
    for m in agents:
        v = "—"
        if val is not None and m in val.index:
            r = val.loc[m]
            v = f"{r[f'{ATT}_mean']:.1f}" + ("" if m in RULES else f" ± {r[f'{ATT}_std']:.1f}")
        if m in RULES:
            tmin, params = "—", "0"
        else:
            tr = training_summaries(args.train_dir, train_model(spec, m), spec["tag"], seeds)
            tmin = f"{tr['training_time_s'].mean() / 60:.1f}" if len(tr) else "—"
            params = f"{int(tr['params'].iloc[0]):,}" if len(tr) else "—"
        rows.append(
            [label(m), v, cell(df, m, "clean", ATT), cell(df, m, "clean", WAIT),
             cell(df, m, "clean", "avg_queue_veh", 2), cell(df, m, "clean", "throughput_veh", 0),
             cell(df, m, "clean", MAXW, 0), tmin, params]
        )  # fmt: skip
        recs.append({"model": m, "validation": v, "training_time_min": tmin, "params": params})
    split = spec["split"]
    lines = header(
        f"Main comparison — {spec['dataset']} `{split}`, clean detectors (ROADMAP 7.1)",
        spec,
        "Validation column: `docs/results/val_phase6.md` (optimistic for learned models: used "
        "for checkpoint, (K, d) and p selection). Training time = wall time per run on CPU "
        "with 5 runs in parallel, so compare it only roughly.",
    )
    lines += md_table(
        ["Model", "Validation travel time (s)", f"{split.capitalize()} travel time (s)",
         "Avg waiting time (s)", "Avg queue (veh / lane)", "Throughput (veh)",
         "Max per-vehicle wait (s)", "Training time (min / run)", "Params"],
        rows,
    )  # fmt: skip

    verdicts: dict = {}
    lines += ["## Hypotheses (rules fixed before the runs: ROADMAP Phase 7 set-up)", ""]
    need = {"ugmarl", "idqn", "max_pressure"}
    if need <= set(spec["models"]):
        ug = vals(df, "ugmarl", "clean", ATT)
        r = hyp.h1(ug, vals(df, "idqn", "clean", ATT), vals(df, "max_pressure", "clean", ATT))
        verdicts["H1"] = r["verdict"]
        lines.append(
            f"- **H1 (performance): {r['verdict']}.** UG-MARL "
            f"{cell(df, 'ugmarl', 'clean', ATT)} s; "
            f"whole CI below Max-Pressure ({cell(df, 'max_pressure', 'clean', ATT)}): "
            f"{'yes' if r['below_max_pressure'] else 'no'}; whole CI below IDQN's CI "
            f"({cell(df, 'idqn', 'clean', ATT)}): {'yes' if r['below_idqn'] else 'no'}."
        )
        if "dqn" in spec["models"]:
            c = hyp.compare(ug, vals(df, "dqn", "clean", ATT))
            d = np.mean(ug) - np.mean(vals(df, "dqn", "clean", ATT))
            verdicts["vs_dqn"] = c
            lines.append(
                f"- **Against DQN (not part of H1): {c}** by CI overlap "
                f"(DQN {cell(df, 'dqn', 'clean', ATT)}; UG-MARL − DQN = {d:+.1f} s)."
            )
        mo = hyp.minimum_outcome(
            vals(df, "ugmarl", "clean", MAXW), vals(df, "max_pressure", "clean", MAXW)
        )
        verdicts["minimum_outcome"] = bool(mo["met"])
        lines.append(
            f"- **Minimum acceptable outcome: {'met' if mo['met'] else 'not met'}.** Mean max "
            f"per-vehicle wait: UG-MARL {mo['ugmarl']:.0f} s, Max-Pressure "
            f"{mo['max_pressure']:.0f} s."
        )
    if "ugmarl-noattn" in spec["models"]:
        r = hyp.h3(vals(df, "ugmarl", "clean", ATT), vals(df, "ugmarl-noattn", "clean", ATT))
        verdicts["H3"] = r["verdict"]
        lines.append(
            f"- **H3 (coordination): {r['verdict']}.** UG-MARL {cell(df, 'ugmarl', 'clean', ATT)} "
            f"vs −attention {cell(df, 'ugmarl-noattn', 'clean', ATT)} s."
        )
    lines += ["- H2 (safety / self-correction): see the robustness table.", ""]
    st = stats_frame(df[(df["condition"] == "clean") & df["model"].isin(agents)],
                     [ATT, WAIT, "avg_queue_veh", "throughput_veh", MAXW])  # fmt: skip
    write(args.out_dir, f"{prefix}_main", lines, st.merge(pd.DataFrame(recs), on="model"))
    return verdicts


# --- 7.2 ablation ------------------------------------------------------------------------


def ablation_table(df, spec, args, prefix) -> None:
    variants = [m for m in VARIANTS if m in spec["models"]]
    conds = list(dict.fromkeys(df["condition"]))
    full = vals(df, "ugmarl", "clean", ATT)
    rows = []
    for m in variants:
        d = "—" if m == "ugmarl" else f"{np.mean(vals(df, m, 'clean', ATT)) - np.mean(full):+.1f}"
        tr = training_summaries(args.train_dir, train_model(spec, m), spec["tag"], spec["seeds"])
        rows.append(
            [label(m), cell(df, m, "clean", ATT), d, cell(df, m, "clean", WAIT),
             cell(df, m, "clean", MAXW, 0), cell(df, m, "clean", "fallback_rate", 3),
             f"{int(tr['params'].iloc[0]):,}" if len(tr) else "—"]
        )  # fmt: skip
    lines = header(
        f"Ablation — {spec['dataset']} `{spec['split']}` (ROADMAP 7.2)",
        spec,
        "−gate = the full model's checkpoints with the gate off; −attention = no neighbour "
        "input, own τ; −ensemble = K = 1, no σ and no gate.",
    )
    lines += ["## Clean detectors", ""]
    lines += md_table(
        ["Variant", "Travel time (s)", "Δ vs full (s, difference of means)",
         "Avg waiting time (s)", "Max per-vehicle wait (s)", "Fallback rate", "Params"],
        rows,
    )  # fmt: skip
    if "ugmarl-nogate" in variants:
        p = hyp.paired(full, vals(df, "ugmarl-nogate", "clean", ATT))
        lines += [
            f"Gate on − gate off, per seed (same checkpoints), clean travel time: "
            f"{fmt(p, 2)} s.",
            "",
        ]
    lines += ["## Travel time (s) by condition", ""]
    lines += md_table(
        ["Variant", *conds], [[label(m), *(cell(df, m, c, ATT) for c in conds)] for m in variants]
    )
    lines += ["## Max per-vehicle wait (s), mean over seeds, by condition", ""]
    lines += md_table(
        ["Variant", *conds],
        [[label(m), *(f"{np.mean(vals(df, m, c, MAXW)):.0f}" for c in conds)] for m in variants],
    )
    st = stats_frame(df[df["model"].isin(variants)], [ATT, WAIT, MAXW, "fallback_rate"])
    write(args.out_dir, f"{prefix}_ablation", lines, st)


# --- 7.3 robustness ----------------------------------------------------------------------


def robustness_table(df, spec, args, prefix) -> dict:
    models = list(spec["models"])
    conds = list(dict.fromkeys(df["condition"]))
    others = [c for c in conds if c != "clean"]

    def grid(title, fn, columns=conds):
        return [f"## {title}", "",
                *md_table(["Model", *columns], [[label(m), *(fn(m, c) for c in columns)]
                                                for m in models])]  # fmt: skip

    def mean(m, c, metric):
        return float(np.mean(vals(df, m, c, metric)))

    lines = header(
        f"Robustness — {spec['dataset']} `{spec['split']}`, model × condition (ROADMAP 7.3)",
        spec,
        "Conditions are applied one at a time and act on what every controller observes "
        "(protocol §6): noise = Gaussian on capacity-scaled lane values, drop = lane reading "
        "set to 0, surge = each vehicle duplicated with probability 0.5 (demand ×1.5). "
        "Rule-based controllers are deterministic on the clean flow only.",
    )
    lines += grid("Average travel time (s)", lambda m, c: cell(df, m, c, ATT))
    lines += grid("Travel-time increase over the clean flow (s, difference of means)",
                  lambda m, c: f"{mean(m, c, ATT) - mean(m, 'clean', ATT):+.1f}",
                  others)  # fmt: skip
    lines += grid("Maximum per-vehicle wait (s), mean over seeds",
                  lambda m, c: f"{mean(m, c, MAXW):.0f}")  # fmt: skip
    lines += grid("Throughput (vehicles that left the network), mean over seeds",
                  lambda m, c: f"{mean(m, c, 'throughput_veh'):.0f}")  # fmt: skip
    lines += grid("Fallback rate (share of decisions taken by Max-Pressure)",
                  lambda m, c: f"{mean(m, c, 'fallback_rate'):.3f}")  # fmt: skip

    ref = [m for m in AGENTS if m in models]
    means = pd.DataFrame(
        [{"model": m, "condition": c, "mean": mean(m, c, ATT)} for m in models for c in conds]
    )
    regret = hyp.regret_table(means, ref)
    summ = hyp.regret_summary(regret).set_index("model")
    piv = regret.pivot(index="model", columns="condition", values="regret")
    lines += [
        "## Regret (s): mean travel time − the lowest mean among the five agents in that "
        "condition",
        "",
        "Descriptive, no threshold (reading fixed before the runs). 0 = best agent of the "
        "condition; ablation rows are measured against the same five agents, so they can "
        "be negative.",
        "",
        *md_table(
            ["Model", *conds, "Largest", "Mean"],
            [[label(m), *(f"{piv.loc[m, c]:+.1f}" for c in conds),
              f"{summ.loc[m, 'max_regret']:+.1f} ({summ.loc[m, 'worst_condition']})",
              f"{summ.loc[m, 'mean_regret']:+.1f}"] for m in models],
        ),
    ]  # fmt: skip
    verdicts: dict = {}
    order = summ.loc[ref].sort_values("max_regret")
    verdicts["smallest_worst_case_regret"] = order.index[0]
    lines += [
        f"Smallest worst-case regret among the five agents: **{label(order.index[0])}** "
        f"({order.iloc[0]['max_regret']:+.1f} s); order: "
        + ", ".join(f"{label(m)} {r['max_regret']:+.1f}" for m, r in order.iterrows())
        + ".",
        "",
    ]
    if {"ugmarl", "ugmarl-nogate"} <= set(models) and NOISE in conds:
        def side(m):
            return {
                "wait_clean": vals(df, m, "clean", MAXW),
                "wait_noise": vals(df, m, NOISE, MAXW),
                "tt_clean": vals(df, m, "clean", ATT),
                "tt_noise": vals(df, m, NOISE, ATT),
            }

        g, n = side("ugmarl"), side("ugmarl-nogate")
        r = hyp.h2(g, n)
        verdicts["H2"] = r["verdict"]
        yn = {True: "yes", False: "no"}
        lines += [
            "## H2 (safety / self-correction): gate vs −gate, same checkpoints",
            "",
            f"**Verdict: {r['verdict']}** (supported = (i), (ii), (iii); partly supported = "
            "(ii) and (iii) only).",
            "",
            *md_table(
                ["Criterion", "With gate", "Without gate", "Gate better?",
                 "Paired difference gate − no gate (per seed)"],
                [["(i) max wait, clean (s)", f"{np.mean(g['wait_clean']):.0f}",
                  f"{np.mean(n['wait_clean']):.0f}", yn[r["i_max_wait_clean_lower"]],
                  fmt(r["paired_wait_clean"], 0)],
                 [f"(ii) max wait, {NOISE} (s)", f"{np.mean(g['wait_noise']):.0f}",
                  f"{np.mean(n['wait_noise']):.0f}", yn[r["ii_max_wait_noise_lower"]],
                  fmt(r["paired_wait_noise"], 0)],
                 [f"(iii) travel-time increase clean → {NOISE} (s)", f"{r['increase_gate']:+.1f}",
                  f"{r['increase_no_gate']:+.1f}", yn[r["iii_degradation_smaller"]],
                  fmt(r["paired_increase"], 1)]],
            ),
        ]  # fmt: skip
    if {"ugmarl", "max_pressure"} <= set(models):
        lines += ["## Minimum outcome by condition: mean max wait, UG-MARL vs Max-Pressure", ""]
        lines += md_table(
            ["", *conds],
            [["UG-MARL (s)", *(f"{mean('ugmarl', c, MAXW):.0f}" for c in conds)],
             ["Max-Pressure (s)", *(f"{mean('max_pressure', c, MAXW):.0f}" for c in conds)],
             ["UG-MARL ≤ Max-Pressure", *("yes" if mean("ugmarl", c, MAXW)
                                          <= mean("max_pressure", c, MAXW) else "no"
                                          for c in conds)]],
        )  # fmt: skip
    st = stats_frame(df, [ATT, WAIT, MAXW, "wait_p95_s", "wait_p99_s", "throughput_veh",
                          "fallback_rate"])  # fmt: skip
    st = st.merge(regret[["model", "condition", "regret"]], on=["model", "condition"])
    write(args.out_dir, f"{prefix}_robustness", lines, st)
    return verdicts


# --- 7.5 efficiency ----------------------------------------------------------------------


def efficiency_table(df, spec, args, prefix, held: pd.DataFrame | None) -> None:
    rows, recs = [], []
    for m in spec["models"]:
        lat = cell(df, m, "clean", "decision_latency_ms", 3)
        p95 = f"{np.mean(vals(df, m, 'clean', 'decision_latency_ms_p95')):.2f}"
        hz = "—"
        if held is not None and m in set(held["model"]):
            hz = f"{held[held['model'] == m]['decision_latency_ms'].mean():.2f}"
        agent = (spec["models"][m] or {}).get("agent", m)
        if agent in RULES:
            tmin, params, size = "—", "0", "—"
        else:
            tm = train_model(spec, m)
            tr = training_summaries(args.train_dir, tm, spec["tag"], spec["seeds"])
            tmin = f"{tr['training_time_s'].mean() / 60:.1f}" if len(tr) else "—"
            params = f"{int(tr['params'].iloc[0]):,}" if len(tr) else "—"
            ck = args.train_dir / f"{tm}_{spec['tag']}_s{spec['seeds'][0]}/checkpoints/best.pt"
            size = f"{ck.stat().st_size / 1e6:.2f}" if ck.is_file() else "—"
        rows.append([label(m), lat, p95, hz, tmin, params, size])
        recs.append({"model": m, "latency_ms": lat, "latency_p95_ms": p95,
                     "latency_heldout_ms": hz, "training_time_min": tmin, "params": params,
                     "checkpoint_mb": size})  # fmt: skip
    lines = header(
        f"Efficiency — {spec['dataset']} `{spec['split']}` clean runs (ROADMAP 7.5)",
        spec,
        "Decision latency = wall-clock time of one joint decision (a phase for every "
        "intersection), CPU, one torch thread, measured in the evaluation runs with one "
        "process at a time. Training time = wall time of one run (100 episodes + 20 "
        "validation episodes) on CPU while 5 runs shared the machine — a rough comparison "
        "only. The checkpoint file also stores the target network and the optimiser state. "
        "**GPU memory: not used** — training and inference run on the CPU (worklog/016: CPU "
        "was faster than CUDA for these small networks). −gate uses the full model's "
        "checkpoints.",
    )
    lines += md_table(
        ["Model", "Decision latency (ms), 12 intersections", "p95 latency (ms)",
         "Decision latency (ms), Hangzhou 16 intersections", "Training time (min / run)",
         "Params", "Checkpoint (MB)"],
        rows,
    )  # fmt: skip
    write(args.out_dir, f"{prefix}_efficiency", lines, pd.DataFrame(recs))


# --- 7.6 safety and explainability -------------------------------------------------------


def decisions(df: pd.DataFrame, model: str, cond: str) -> pd.DataFrame | None:
    g = df[(df["model"] == model) & (df["condition"] == cond)]
    frames = []
    for _, r in g.iterrows():
        f = Path(r["run_dir"]) / f"decisions_s{int(r['seed'])}.csv"
        if f.is_file():
            frames.append(pd.read_csv(f).assign(seed=int(r["seed"])))
    return pd.concat(frames, ignore_index=True) if frames else None


def gate_stats(d: pd.DataFrame) -> dict:
    fb = d["fallback"].astype(bool)
    differ = d["mp_phase"] != d["greedy_phase"]
    return {
        "decisions": len(d),
        "fallback_rate": float(fb.mean()),
        "sigma_mean": float(d["sigma"].mean()),
        "sigma_over_tau": float((d["sigma"] > d["tau"]).mean()) if d["tau"].notna().any()
        else float("nan"),
        "policy_differs_from_mp": float(differ.mean()),
        "fired_and_differs": float((fb & differ).mean()),
        "differs_given_fired": float(differ[fb].mean()) if fb.any() else float("nan"),
    }  # fmt: skip


def safety_table(df, spec, args, prefix, held: pd.DataFrame | None) -> None:
    models = list(spec["models"])
    conds = list(dict.fromkeys(df["condition"]))
    lines = header(
        f"Safety and explainability — {spec['dataset']} `{spec['split']}` (ROADMAP 7.6)",
        spec,
        "σ, the gate and the attention weights describe what the model computed: they are "
        "**associations, not causes**.",
    )
    for metric, title in ((MAXW, "Maximum per-vehicle wait (s)"),
                          ("wait_p99_s", "99th percentile of per-vehicle wait (s)"),
                          ("wait_p95_s", "95th percentile of per-vehicle wait (s)")):  # fmt: skip
        if metric not in df:
            continue
        lines += [f"## {title}, mean ± std over seeds", ""]
        lines += md_table(
            ["Model", *conds],
            [[label(m), *(f"{np.mean(vals(df, m, c, metric)):.0f} ± "
                          f"{np.std(vals(df, m, c, metric), ddof=1):.0f}" for c in conds)]
             for m in models],
        )  # fmt: skip

    recs = []
    logged = [m for m in models if decisions(df, m, conds[0]) is not None]
    if logged:
        lines += [
            "## Gate statistics (per-decision logs, all seeds pooled)",
            "",
            "Fallback = decisions handed to Max-Pressure. \"Policy ≠ MP\" = share of all "
            "decisions where the learned greedy phase differs from the Max-Pressure phase; "
            "\"gate changed the action\" = share of all decisions where the gate fired **and** "
            "the two phases differ; \"≠ MP when fired\" = among gate firings, the share where "
            "the fallback changed the action.",
            "",
        ]
        rows = []
        for m in logged:
            for c in conds:
                d = decisions(df, m, c)
                if d is None:
                    continue
                s = gate_stats(d)
                recs.append({"model": m, "condition": c, **s})
                nan = lambda x, k=3: "—" if np.isnan(x) else f"{x:.{k}f}"  # noqa: E731
                rows.append(
                    [label(m), c, f"{s['decisions']}", f"{s['fallback_rate']:.3f}",
                     f"{s['sigma_mean']:.4f}", nan(s["sigma_over_tau"]),
                     f"{s['policy_differs_from_mp']:.3f}", f"{s['fired_and_differs']:.3f}",
                     nan(s["differs_given_fired"])]
                )  # fmt: skip
        lines += md_table(
            ["Model", "Condition", "Decisions", "Fallback rate", "Mean σ", "Share σ > τ",
             "Policy ≠ MP", "Gate changed the action", "≠ MP when fired"],
            rows,
        )  # fmt: skip
    if "ugmarl" in logged:
        show = [c for c in ("clean", NOISE) if c in conds] or conds[:1]
        per = {c: decisions(df, "ugmarl", c) for c in show}
        ids = sorted(per[show[0]]["iid"].unique())
        lines += ["## UG-MARL fallback rate per intersection", ""]
        lines += md_table(
            ["Intersection", *show],
            [[i, *(f"{per[c][per[c]['iid'] == i]['fallback'].mean():.3f}" for c in show)]
             for i in ids],
        )  # fmt: skip
        lines += ["## UG-MARL fallback rate per 10-minute window", ""]
        win = {c: per[c].assign(w=(per[c]["t"] // 600).astype(int)).groupby("w")["fallback"].mean()
               for c in show}  # fmt: skip
        lines += md_table(
            ["Window (min)", *show],
            [[f"{w * 10}–{w * 10 + 10}", *(f"{win[c].get(w, float('nan')):.3f}" for c in show)]
             for w in sorted(win[show[0]].index)],
        )  # fmt: skip
        d = per[show[0]]
        lines += [
            f"## UG-MARL attention weights, `{show[0]}` (mean over decisions)",
            "",
            "Slots: the intersection itself and its neighbours to the E, N, W, S; a missing "
            "neighbour (network edge) has weight 0 and is left out of that slot's mean.",
            "",
        ]
        att = [d[f"attn_{s}"].where(d[f"attn_{s}"] > 0) if s != "self" else d["attn_self"]
               for s in SLOTS]  # fmt: skip
        lines += md_table(
            ["", *SLOTS],
            [["Mean weight", *(f"{a.mean():.3f}" for a in att)],
             ["Std over decisions", *(f"{a.std():.3f}" for a in att)]],
        )  # fmt: skip
        by = d.groupby("iid")[[f"attn_{s}" for s in SLOTS]].mean()
        lines += ["Per intersection (mean weight; 0 = no neighbour in that direction):", ""]
        lines += md_table(
            ["Intersection", *SLOTS],
            [[i, *(f"{by.loc[i, f'attn_{s}']:.3f}" for s in SLOTS)] for i in by.index],
        )
    if held is not None and "ugmarl" in set(held["model"]):
        flows = list(dict.fromkeys(held["condition"]))
        lines += ["## Held-out city: UG-MARL gate (zero-shot, τ from Jinan validation)", ""]
        rows = []
        for m in [x for x in ("ugmarl", "ugmarl-noattn") if x in set(held["model"])]:
            rows.append([label(m), *(f"{np.mean(vals(held, m, f, 'fallback_rate')):.3f}"
                                     for f in flows)])  # fmt: skip
        lines += md_table(["Fallback rate", *flows], rows)
    write(args.out_dir, f"{prefix}_safety_explain", lines, pd.DataFrame(recs))


