"""Phase 5 validation table: rule baselines vs RL baselines on Jinan val (plan D10).

    python scripts/val_table.py [--agents fixed_time max_pressure dqn idqn] [--tag final]

Reads the latest clean ``results/eval/<agent>_jinan-val_*`` run of every agent (learned
agents evaluated with ``evaluate.py --checkpoint results/train/<agent>_<tag>_s{seed}/...``)
and the training summaries; writes ``docs/results/val_phase5.{csv,md}``. Dev numbers (WSL).
"""

from __future__ import annotations

import argparse
import sys

import pandas as pd

from trafficrl.agents import LEARNED_AGENTS
from trafficrl.data.splits import REPO_ROOT
from trafficrl.eval.report import fmt, latest_eval_run, metric_stats, training_summaries
from trafficrl.utils.plotting import CONTROLLER_LABEL

OUT = REPO_ROOT / "docs" / "results"
METRICS = [
    ("avg_travel_time_s", "Avg travel time (s)"),
    ("avg_waiting_time_s", "Avg waiting time (s)"),
    ("max_waiting_time_s", "Max per-vehicle wait (s)"),
    ("throughput_veh", "Throughput (veh)"),
    ("decision_latency_ms", "Decision latency (ms)"),
]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--agents", nargs="+", default=["fixed_time", "max_pressure", "dqn", "idqn"])
    ap.add_argument("--tag", default="final", help="training run tag: <agent>_<tag>_s<seed>")
    args = ap.parse_args(argv)

    rows, md_rows = [], []
    for agent in args.agents:
        run = latest_eval_run(REPO_ROOT / "results" / "eval", agent, "jinan", "val")
        mcsv = run / "metrics.csv"
        seeds = pd.read_csv(mcsv)["seed"].tolist()
        row = {"model": agent, "eval_run": run.name, "seeds": " ".join(map(str, seeds))}
        md = [CONTROLLER_LABEL.get(agent, agent)]
        for key, _ in METRICS:
            st = metric_stats(mcsv, key)
            row.update({f"{key}_{k}": st[k] for k in ("mean", "std", "ci95_low", "ci95_high")})
            md.append(fmt(st, 2 if key == "decision_latency_ms" else 1))
        if agent in LEARNED_AGENTS:
            tr = training_summaries(REPO_ROOT / "results" / "train", agent, args.tag, seeds)
            row.update(
                training_time_min=tr["training_time_s"].mean() / 60,
                params=int(tr["params"].iloc[0]),
            )
            md += [f"{row['training_time_min']:.1f}", f"{row['params']:,}"]
        else:
            row.update(training_time_min=0.0, params=0)
            md += ["—", "0"]
        rows.append(row)
        md_rows.append(md)

    OUT.mkdir(parents=True, exist_ok=True)
    pd.DataFrame(rows).to_csv(OUT / "val_phase5.csv", index=False)
    head = ["Model", *(h for _, h in METRICS), "Training time (min / run)", "Params"]
    lines = [
        "# Phase 5 — validation results (dev, WSL)",
        "",
        "Jinan `real_2000` (validation flow), 3600 s, Δt = 15 s. Mean ± std [95 % CI, Student t]"
        " over the evaluation seeds; a learned agent's seed s is evaluated with the checkpoint"
        " trained with seed s (best validation episode). Rule-based baselines are deterministic."
        " Generated by `scripts/val_table.py`; **dev numbers** (WSL) — reported numbers come"
        " from native Ubuntu in Phase 7 (Decision Log 11 Nov). Validation was also used for"
        " checkpoint and hyperparameter selection, so learned-agent scores are optimistic."
        " Training time = wall time of 100 episodes + 20 val episodes on CPU while 2–5 runs"
        " shared the machine (one IDQN run alone: 12 min), so compare it only roughly.",
        "",
        "| " + " | ".join(head) + " |",
        "|" + "---|" * len(head),
        *("| " + " | ".join(r) + " |" for r in md_rows),
        "",
    ]
    (OUT / "val_phase5.md").write_text("\n".join(lines))
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
