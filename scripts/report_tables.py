"""Write the report's LaTeX tables and number macros from ``docs/results/*.csv``.

A pure reader (ROADMAP 9.1): no simulation, no selection. Run it after
``scripts/final_tables.py``; ``tests/scripts/test_report_sources.py`` checks that the
tracked files under ``report/`` are up to date.

    python scripts/report_tables.py            # report/tables/*.tex, report/generated/numbers.tex
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import pandas as pd

from trafficrl.eval import latex

REPO_ROOT = Path(__file__).resolve().parents[1]


def build(results_dir: Path) -> dict[str, str]:
    """``{relative output path: file content}``."""

    def read(name: str) -> pd.DataFrame:
        return pd.read_csv(results_dir / f"{name}.csv", dtype={"params": str})

    main, abl, rob = read("test_main"), read("test_ablation"), read("test_robustness")
    held, held_all = read("heldout_generalisation"), read("heldout_generalisation_all")
    eff = pd.read_csv(results_dir / "test_efficiency.csv", dtype=str)
    params = dict(zip(eff["model"], eff["params"], strict=True))
    note = "% Generated by scripts/report_tables.py from docs/results/*.csv -- do not edit.\n"
    tables = {
        "main": latex.table_main(main),
        "ablation": latex.table_ablation(abl, params),
        "robustness": latex.table_robustness(rob),
        "heldout": latex.table_heldout(held, held_all),
        "efficiency": latex.table_efficiency(eff),
    }
    out = {f"tables/{k}.tex": note + v for k, v in tables.items()}
    out["generated/numbers.tex"] = latex.render_macros(
        latex.number_macros(main, rob, held, held_all)
    )
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--results-dir", type=Path, default=REPO_ROOT / "docs" / "results")
    ap.add_argument("--out", type=Path, default=REPO_ROOT / "report")
    args = ap.parse_args(argv)
    try:
        files = build(args.results_dir)
    except FileNotFoundError as e:
        print(f"error: {e}", file=sys.stderr)
        return 1
    for rel, text in files.items():
        path = args.out / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
